export const formatTimestamp = (unixTimestamp) => {
  if (!unixTimestamp) return "Unknown Date";
  
  const date = new Date(unixTimestamp * 1000); // Instagram timestamps are in seconds
  
  return new Intl.DateTimeFormat('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric'
  }).format(date);
};

export const formatNumber = (num) => {
  if (num >= 1000000) {
    return (num / 1000000).toFixed(1) + 'M';
  }
  if (num >= 1000) {
    return (num / 1000).toFixed(1) + 'k';
  }
  return num.toString();
};
